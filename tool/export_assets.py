#!/usr/bin/env python3
"""Exports the SVG art in assets_src/ to PNG and writes assets/manifest.json.

Each source becomes three PNGs for Flutter's resolution-aware loading:
    assets/<dir>/<name>.png        1x (logical size)
    assets/<dir>/2.0x/<name>.png   2x
    assets/<dir>/3.0x/<name>.png   3x
Sources marked "single" (launcher icon, native splash) export once at their
own size.

Requires the resvg CLI (brew install resvg). Run from anywhere:
    node tool/assets/build_art.mjs && python3 tool/export_assets.py
"""
import json
import os
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, 'assets')
SPECS = os.path.join(ROOT, 'assets_src', 'specs.json')
GENERATED_DIRS = ['images', 'sprites', 'launcher']


def render(src, out, zoom):
    os.makedirs(os.path.dirname(out), exist_ok=True)
    subprocess.run(['resvg', '--zoom', str(zoom), src, out], check=True, capture_output=True)


def scaled(out, scale):
    head, name = os.path.split(out)
    return out if scale == 1 else os.path.join(head, f'{scale}.0x', name)


def png_size(path):
    with open(path, 'rb') as f:
        data = f.read(24)
    return int.from_bytes(data[16:20], 'big'), int.from_bytes(data[20:24], 'big')


def main():
    if shutil.which('resvg') is None:
        sys.exit('resvg not found: brew install resvg')
    with open(SPECS) as f:
        specs = json.load(f)
    for d in GENERATED_DIRS:
        shutil.rmtree(os.path.join(ASSETS, d), ignore_errors=True)

    jobs = []
    for s in specs:
        if not s.get('src'):
            continue
        src = os.path.join(ROOT, s['src'])
        out = os.path.join(ROOT, s['out'])
        scales = [1] if s.get('single') else [1, 2, 3]
        s['files'] = []
        for scale in scales:
            target = scaled(out, scale)
            jobs.append((src, target, scale))
            s['files'].append(os.path.relpath(target, ROOT))
    with ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
        list(pool.map(lambda j: render(*j), jobs))

    entries = []
    for s in specs:
        files = s.pop('files', [s['out']])
        entry = {
            'path': s['out'],
            'source': s.get('src'),
            'files': files,
            'size': s['size'],
            'modes': s['modes'],
            'screens': s['screens'],
            'group': s['group'],
            'bundled': s.get('bundled', True),
        }
        for key in ('anchor', 'nineSlice', 'tile', 'theme', 'note', 'frameMs', 'labelColor', 'animal', 'background'):
            if key in s:
                entry[key] = s[key]
        if s.get('src'):
            w, h = png_size(os.path.join(ROOT, files[0]))
            if s.get('single'):
                assert [w, h] == s['size'], (s['out'], w, h)
            else:
                assert abs(w - s['size'][0]) <= 1 and abs(h - s['size'][1]) <= 1, (s['out'], w, h)
        entries.append(entry)

    # Non-image assets are listed too, so the manifest covers every file in assets/.
    def listed(rel_dir, group, exts, extra=None):
        base = os.path.join(ASSETS, rel_dir)
        if not os.path.isdir(base):
            return
        for name in sorted(os.listdir(base)):
            if os.path.splitext(name)[1] in exts:
                rel = f'assets/{rel_dir}/{name}'
                e = {'path': rel, 'source': None, 'files': [rel], 'modes': ['n/a'], 'screens': ['all'], 'group': group, 'bundled': True}
                e.update(extra(name) if extra else {})
                entries.append(e)

    listed('boards', 'board_layout', {'.json'}, lambda n: {'screens': ['game', 'player_setup', 'board_select']})
    listed('themes', 'board_palette', {'.json'}, lambda n: {'modes': ['light', 'dark']})
    listed('fonts', 'font', {'.ttf', '.txt'})
    listed('audio', 'audio', {'.ogg', '.m4a', '.md'})

    manifest = {
        'schemaVersion': 1,
        'note': 'Generated by tool/export_assets.py. size is the 1x logical size in px; files lists every scale.',
        'assets': entries,
    }
    with open(os.path.join(ASSETS, 'manifest.json'), 'w') as f:
        json.dump(manifest, f, indent=1)
        f.write('\n')
    pngs = sum(len(e['files']) for e in entries if e['path'].endswith('.png'))
    print(f'{len(entries)} manifest entries, {pngs} PNG files')


if __name__ == '__main__':
    main()
